function watermark(doc) {
  doc.save();
  doc.rotate(-30, { origin: [300, 420] });
  doc.font('Helvetica-Bold').fontSize(60).fillColor('#e2e8f0').opacity(0.55).text('SAMPLE', 90, 380, { width: 420, align: 'center' });
  doc.restore();
  doc.opacity(1);
}

