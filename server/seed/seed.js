// ─── Main ────────────────────────────────────────────────────────────────────
async function clearUploads() {
  if (isCloudinaryEnabled) return;
  const entries = await fs.readdir(UPLOAD_ROOT, { withFileTypes: true }).catch(() => []);
  await Promise.all(
    entries.filter((e) => e.isDirectory()).map((e) => fs.rm(path.join(UPLOAD_ROOT, e.name), { recursive: true, force: true }))
  );
}

async function main() {
  const started = Date.now();
  await connectDB();

  if (CATALOG_ONLY) {
    await seedCatalog();
    await Promise.all([VehicleType, FuelType, MaintenanceCategory, MaintenanceTemplate].map((m) => m.syncIndexes()));
    console.log('\n✔ Catalog loaded.');
    return;
  }

  step('Resetting database');
  await mongoose.connection.dropDatabase();
  await clearUploads();
  const models = [User, VehicleType, FuelType, MaintenanceCategory, MaintenanceTemplate, Vehicle, MaintenanceTask, ServiceRecord, Expense, Document, Reminder, Notification];
  await Promise.all(models.map((m) => m.syncIndexes()));

  await seedCatalog();

  step('Creating demo & admin accounts');
  // Admin sign-in can be set per environment (SEED_ADMIN_EMAIL / SEED_ADMIN_PASSWORD in server/.env).
  const adminUser = {
    ...ADMIN_USER,
    email: (process.env.SEED_ADMIN_EMAIL || ADMIN_USER.email).trim().toLowerCase(),
    password: process.env.SEED_ADMIN_PASSWORD || ADMIN_USER.password,
  };
  const admin = await User.create({ ...adminUser, lastLoginAt: NOW });
  await User.collection.updateOne({ _id: admin._id }, { $set: { createdAt: monthsAgo(20) } });
  const demo = await User.create({ ...DEMO_USER, lastLoginAt: NOW });
  await User.collection.updateOne({ _id: demo._id }, { $set: { createdAt: monthsAgo(18.5) } });
  info(`Demo:  ${DEMO_USER.email} / ${DEMO_USER.password}`);
  info(`Admin: ${adminUser.email} / ${adminUser.password}`);

  await seedDemoFleet(demo);
  await seedPersonalItems(demo);
  await polishNotifications(demo);
  await seedExtraUsers();
  await User.updateMany({}, { $set: { lastStatusSyncAt: new Date() } });

  const counts = await Promise.all(models.map(async (m) => [m.modelName, await m.countDocuments()]));
  step('Done');
  console.table(Object.fromEntries(counts));
  console.log(`\n✔ Seed completed in ${((Date.now() - started) / 1000).toFixed(1)}s`);
  console.log(`  Sign in → ${DEMO_USER.email} / ${DEMO_USER.password}   (admin: ${adminUser.email} / ${adminUser.password})\n`);
}

main()
  .catch((error) => {
    console.error('\n✖ Seed failed:', error);
    process.exitCode = 1;
  })
  .finally(() => mongoose.disconnect());
