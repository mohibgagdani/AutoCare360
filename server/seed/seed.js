async function skipAt(task, vehicle, date, odometer, reason) {
  task.status = 'skipped';
  task.isOpen = false;
  task.dueBy = null;
  task.skippedAt = date;
  task.skipReason = reason;
  await task.save();
  const draft = buildOccurrence(taskFields(task), {
    vehicle: { _id: vehicle._id, owner: vehicle.owner, odometer },
    lastDate: date,
    lastOdometer: odometer,
    now: date,
  });
  await MaintenanceTask.create(draft);
}

const unitFor = (typeCode) => (vehicleTypes.find((t) => t.code === typeCode)?.usageUnit === 'hours' ? 'hrs' : 'km');
const groupFor = (typeCode) => vehicleTypes.find((t) => t.code === typeCode)?.group;

async function simulateService(owner, vehicle, def, event, odoAt, invoiceCounter) {
  const date = monthsAgo(event.monthsAgo);
  const odometer = odoAt(date);
  await Vehicle.updateOne({ _id: vehicle._id }, { $set: { odometer } });

  const open = await MaintenanceTask.find({ vehicle: vehicle._id, isOpen: true });
  let selected;
  if (event.only) {
    selected = open.filter((t) => event.only.includes(t.code));
  } else {
    selected = open.filter((t) => {
      if (event.leave?.includes(t.code)) return false;
      const { status, progress } = evaluateTask(t, { currentOdometer: odometer, now: date });
      if (event.minor) return status !== 'up_to_date';
      // Workshops also do items that are close to due while the vehicle is in.
      return status !== 'up_to_date' || progress >= 0.7;
    });
  }

  const group = groupFor(def.vehicle.vehicleType);
  const { parts, labour } = buildInvoiceLines(selected, def.vehicle.make, group);
  const allParts = [...parts, ...(event.extraParts || [])];
  const partsCost = allParts.reduce((s, p) => s + p.quantity * p.unitPrice, 0);
  const taxes = roundTo((partsCost + labour) * 0.18, 1);
  const discount = rand() < 0.3 ? roundTo((partsCost + labour) * 0.05, 10) : 0;

  const record = await ServiceRecord.create({
    owner,
    vehicle: vehicle._id,
    serviceDate: date,
    odometer,
    serviceCenter: event.center,
    serviceCenterLocation: event.location,
    mechanic: event.mechanic,
    serviceType: event.type || (event.minor ? 'inspection' : 'periodic_service'),
    maintenanceItems: selected.map((t) => ({ task: t._id, code: t.code, name: t.name, category: t.category })),
    partsReplaced: allParts,
    laborCost: labour,
    taxes,
    discount,
    rating: event.rating,
    notes:
      event.notes ||
      pick([
        'Routine service completed. Vehicle washed and vacuumed.',
        'All fluids topped up. No major issues found.',
        'Service done as per schedule. Advised to monitor tyre wear.',
        'General check-up completed; road test OK.',
      ]),
  });

  const perItem = selected.length ? round2(record.totalCost / selected.length) : undefined;
  for (const task of selected) {
    await completeTask(task, { date, odometer, cost: perItem, serviceRecord: record._id, refresh: false, now: date });
  }

  const invoiceNo = `INV-${date.getFullYear()}-${String(invoiceCounter).padStart(5, '0')}`;
  const buffer = await invoicePdf({
    center: event.center,
    location: event.location,
    invoiceNo,
    date,
    vehicleLabel: `${def.vehicle.make} ${def.vehicle.model} · ${def.vehicle.registrationNumber}`,
    odometer,
    unit: unitFor(def.vehicle.vehicleType),
    parts: allParts,
    labour,
    taxes,
    discount,
    total: record.totalCost,
  });
  record.invoice = await uploadBuffer(buffer, { originalName: `${invoiceNo}.pdf`, mimeType: 'application/pdf', folder: 'invoices' });

  if (record.totalCost > 0) {
    const expense = await Expense.create({
      owner,
      vehicle: vehicle._id,
      category: record.serviceType === 'repair' ? 'repairs' : record.serviceType === 'tyre_service' ? 'tyres' : 'maintenance',
      amount: record.totalCost,
      date,
      odometer,
      description: `${record.serviceType === 'repair' ? 'Repair' : record.serviceType === 'tyre_service' ? 'Tyre service' : 'Periodic service'} · ${event.center}`,
      vendor: event.center,
      paymentMethod: pick(['card', 'upi', 'upi']),
      serviceRecord: record._id,
    });
    record.expense = expense._id;
  }
  await record.save();
  return { record, completed: selected.length, date, odometer };
}

async function simulateDiy(owner, vehicle, date, odometer) {
  await Vehicle.updateOne({ _id: vehicle._id }, { $set: { odometer } });
  // DIY items plus short-interval checks anyone can do (e.g. monthly fleet walk-arounds).
  const open = await MaintenanceTask.find({
    vehicle: vehicle._id,
    isOpen: true,
    $or: [{ serviceMode: 'diy' }, { serviceMode: 'either', intervalMonths: { $lte: 3 } }],
  });
  let done = 0;
  for (const task of open) {
    const { status } = evaluateTask(task, { currentOdometer: odometer, now: date });
    if (status === 'up_to_date') continue;
    if (rand() < 0.1 && task.priority !== 'high') {
      await skipAt(task, vehicle, date, odometer, 'Checked — still in good condition');
    } else {
      const cost = task.estimatedCost ? roundTo(task.estimatedCost * between(0.8, 1.1)) : undefined;
      await completeTask(task, { date, odometer, cost, notes: 'Done at home', refresh: false, now: date });
      if (cost) {
        await Expense.create({
          owner,
          vehicle: vehicle._id,
          category: task.name.toLowerCase().includes('tyre') ? 'tyres' : 'parts',
          amount: cost,
          date,
          odometer,
          description: task.name,
          vendor: 'DIY',
          paymentMethod: 'upi',
        });
      }
    }
    done += 1;
  }
  return done;
}

