// ─── Demo fleet ──────────────────────────────────────────────────────────────
async function seedDemoFleet(user) {
  step('Simulating demo fleet history (this replays ~18 months through the scheduling engine)');
  let invoiceCounter = 1200;
  const summary = [];

  for (const def of demoFleet) {
    const odoAt = buildUsageModel(def);
    const baselineDate = monthsAgo(def.baselineMonthsAgo);
    const baselineOdo = odoAt(baselineDate);

    const vehicle = await Vehicle.create({
      ...def.vehicle,
      owner: user._id,
      purchaseDate: new Date(def.vehicle.purchaseDate),
      purchaseOdometer: def.vehicle.purchaseOdometer || 0,
      odometer: baselineOdo,
      odometerUpdatedAt: baselineDate,
      odometerLogs: [],
    });

    // Tracking starts with a full service at the baseline.
    await syncSchedule(vehicle, {
      now: baselineDate,
      baseline: { date: baselineDate, odometer: baselineOdo, estimated: false },
      notifyAlerts: false,
    });

    for (const h of def.taskHistory || []) {
      const task = await MaintenanceTask.findOne({ vehicle: vehicle._id, code: h.code, isOpen: true });
      if (!task) continue;
      task.lastPerformedDate = new Date(NOW.getTime() - h.daysAgo * DAY);
      task.lastPerformedOdometer = odoAt(task.lastPerformedDate);
      Object.assign(task, computeNextDue(task));
      await task.save();
    }

    // Timeline of service visits + monthly DIY checks.
    const events = def.services.map((s) => ({ kind: 'service', at: monthsAgo(s.monthsAgo), s }));
    for (let m = def.baselineMonthsAgo - 0.8; m > 0.15; m -= 1) {
      if (def.key === 'ace' && m < 3) continue; // the delivery van has been neglected lately
      events.push({ kind: 'diy', at: monthsAgo(m) });
    }
    events.sort((a, b) => a.at - b.at);

    let services = 0;
    let completed = 0;
    let lastRecord = null;
    for (const e of events) {
      if (e.kind === 'service') {
        invoiceCounter += randInt(7, 40);
        const r = await simulateService(user._id, vehicle, def, e.s, odoAt, invoiceCounter);
        services += 1;
        completed += r.completed;
        lastRecord = r;
      } else {
        completed += await simulateDiy(user._id, vehicle, e.at, odoAt(e.at));
      }
    }

    // Running costs and one-off purchases.
    const expenses = runningCosts(user._id, vehicle._id, def, odoAt, baselineDate);
    for (const o of ONE_OFF_EXPENSES[def.key] || []) {
      const date = monthsAgo(o.monthsAgo);
      expenses.push({ owner: user._id, vehicle: vehicle._id, paymentMethod: 'card', odometer: odoAt(date), ...o, date });
    }
    await Expense.insertMany(expenses.map(({ monthsAgo: _m, ...e }) => e));

    // Odometer history: monthly readings since purchase + today.
    const logs = [];
    const purchase = new Date(def.vehicle.purchaseDate);
    for (let d = new Date(purchase); d < NOW; d = addMonths(d, 1)) logs.push({ value: odoAt(d), date: new Date(d), source: 'manual' });
    logs.push({ value: def.currentOdometer, date: NOW, source: 'manual' });
    await Vehicle.updateOne(
      { _id: vehicle._id },
      {
        $set: {
          odometer: def.currentOdometer,
          odometerUpdatedAt: new Date(NOW.getTime() - randInt(1, 4) * DAY),
          odometerLogs: logs.slice(-400),
          ...(lastRecord ? { lastServiceDate: lastRecord.date, lastServiceOdometer: lastRecord.odometer } : {}),
        },
      }
    );
    await Vehicle.collection.updateOne({ _id: vehicle._id }, { $set: { createdAt: baselineDate } });

    // Documents (+ automatic expiry reminders).
    for (const d of def.docs) {
      const issueDate = new Date(NOW.getTime() - d.issuedDaysAgo * DAY);
      const expiryDate = d.expiresInDays !== undefined ? daysFromNow(d.expiresInDays) : null;
      const buffer = await documentPdf({
        title: d.name,
        issuer: d.issuer,
        number: d.number,
        holder: user.name,
        vehicle: `${def.vehicle.make} ${def.vehicle.model} · ${def.vehicle.registrationNumber}`,
        issueDate,
        expiryDate,
      });
      const file = await uploadBuffer(buffer, {
        originalName: `${d.name.replace(/[^a-z0-9]+/gi, '-')}.pdf`,
        mimeType: 'application/pdf',
        folder: 'documents',
      });
      const doc = new Document({
        owner: user._id,
        vehicle: vehicle._id,
        name: d.name,
        type: d.type,
        documentNumber: d.number,
        issuer: d.issuer,
        issueDate,
        expiryDate,
        uploadDate: issueDate > baselineDate ? issueDate : baselineDate,
        reminderDaysBefore: d.reminderDays || 30,
        file,
      });
      await doc.save();
      await syncDocumentReminder(doc);
      await doc.save();
    }

    await refreshVehicle(vehicle._id, { notifyAlerts: true });
    const fresh = await Vehicle.findById(vehicle._id).lean();
    summary.push({
      vehicle: `${def.vehicle.make} ${def.vehicle.model}`,
      odometer: `${def.currentOdometer.toLocaleString('en-IN')} ${unitFor(def.vehicle.vehicleType)}`,
      services,
      itemsCompleted: completed,
      expenses: expenses.length,
      openItems: fresh.openTaskCounts.total,
      overdue: fresh.openTaskCounts.overdue,
      due: fresh.openTaskCounts.due,
      dueSoon: fresh.openTaskCounts.dueSoon,
      health: `${fresh.healthScore} (${fresh.healthLabel})`,
    });
  }
  console.table(summary);
}

