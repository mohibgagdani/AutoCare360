const LABOUR_ONLY = /(inspection|check|scan|report|update|adjust|test|top-up|rotation|alignment|balancing|greasing|lubrication|cleaning|diagnostics|free-play)/i;

function buildInvoiceLines(tasks, make, group) {
  const parts = [];
  let labour = group === 'two_wheeler' ? 350 : ['heavy_commercial', 'agricultural', 'light_commercial'].includes(group) ? 1200 : 850;
  for (const t of tasks) {
    const cost = (t.estimatedCost || 0) * between(0.9, 1.12);
    if (!cost) continue;
    if (LABOUR_ONLY.test(t.name)) {
      labour += cost;
    } else {
      parts.push({
        name: t.name.replace(/\s+(replacement|change)\b/i, '').replace(/\s*\([^)]*\)$/, ''),
        partNumber: `${make.replace(/[^A-Za-z]/g, '').slice(0, 3).toUpperCase()}-${String(hashString(t.code) % 90000 + 10000)}`,
        quantity: 1,
        unitPrice: roundTo(cost * 0.72, 5),
      });
      labour += cost * 0.28;
    }
  }
  return { parts, labour: roundTo(labour, 10) };
}

