// ─── Deterministic randomness ────────────────────────────────────────────────
function mulberry32(seed) {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const hashString = (s) => [...s].reduce((h, c) => Math.imul(31, h) + c.charCodeAt(0), 7) >>> 0;
const rand = mulberry32(360360);
const between = (a, b) => a + rand() * (b - a);
const randInt = (a, b) => Math.floor(between(a, b + 1));
const pick = (arr) => arr[Math.floor(rand() * arr.length)];
const roundTo = (n, step = 10) => Math.round(n / step) * step;
const round2 = (n) => Math.round(n * 100) / 100;
const monthsAgo = (m) => new Date(NOW.getTime() - m * 30.44 * DAY);
