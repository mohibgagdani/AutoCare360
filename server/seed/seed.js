// ─── Catalog ─────────────────────────────────────────────────────────────────
async function seedCatalog() {
  step('Loading catalog');
  await Promise.all([
    FuelType.deleteMany({}),
    VehicleType.deleteMany({}),
    MaintenanceCategory.deleteMany({}),
    MaintenanceTemplate.deleteMany({}),
  ]);
  await FuelType.insertMany(fuelTypes);
  await VehicleType.insertMany(vehicleTypes);
  const cats = await MaintenanceCategory.insertMany(categories);
  const catId = Object.fromEntries(cats.map((c) => [c.code, c._id]));
  const docs = templates.map((t) => {
    if (!catId[t.category]) throw new Error(`Unknown category "${t.category}" in template ${t.code}`);
    return { ...t, category: catId[t.category] };
  });
  await MaintenanceTemplate.insertMany(docs);
  info(`${fuelTypes.length} fuel types · ${vehicleTypes.length} vehicle types · ${categories.length} categories · ${docs.length} templates`);
}

// ─── Usage model (odometer / hour-meter over time) ──────────────────────────
function buildUsageModel(def) {
  const start = new Date(def.vehicle.purchaseDate);
  const days = Math.max(1, Math.ceil((NOW - start) / DAY));
  const local = mulberry32(hashString(def.key));
  const cumulative = new Float64Array(days + 1);
  let total = 0;
  for (let i = 0; i <= days; i += 1) {
    const d = new Date(start.getTime() + i * DAY);
    let w = def.seasonal ? def.seasonal[d.getMonth()] : 1;
    w *= 0.7 + local() * 0.6;
    if (!def.seasonal && d.getDay() === 0) w *= def.vehicle.vehicleType === 'commercial_vehicle' ? 0.15 : 1.35;
    total += w;
    cumulative[i] = total;
  }
  const base = def.vehicle.purchaseOdometer || 0;
  const span = def.currentOdometer - base;
  return (date) => {
    const i = Math.max(0, Math.min(days, Math.floor((new Date(date) - start) / DAY)));
    return Math.round(base + (span * cumulative[i]) / total);
  };
}

